"""Generate explicitly identified namespace migrations; never edit upstream examples."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

import inventory

ROOT = Path(__file__).resolve().parent


def migrate(text):
    for library in ("asio", "cobalt", "beast"):
        text = text.replace(
            f"<boost/{library}/detail/", f"<webcpp/{library}/detail/backend/detail/"
        )
        text = text.replace(f"<boost/{library}", f"<webcpp/{library}")
        text = text.replace(f"boost::{library}", f"webcpp::{library}")
    text = text.replace("BOOST_COBALT_FOR(", "WEBCPP_COBALT_FOR(")
    if "BOOST_ASIO_CONCURRENCY_HINT_" in text:
        # Preserve upstream numeric configuration values explicitly. The Wasm
        # namespace migration must not rely on incidental native Asio includes.
        text = "#include <boost/asio/detail/concurrency_hint.hpp>\n" + text
    if "BOOST_BEAST_VERSION_STRING" in text:
        # The original protocol identification is Boost version metadata, not
        # a dependency on the native Beast engine or its Asio types.
        text = "#include <boost/beast/version.hpp>\n" + text
    if "using namespace boost;" in text:
        for library in ("asio", "cobalt", "beast"):
            # Version/configuration headers can forward-declare Boost namespaces.
            # Qualify the migrated uses so the original broad using-directive
            # cannot make them ambiguous with those native declarations.
            text = re.sub(r"(?<![\w:])" + library + r"::", f"webcpp::{library}::", text)
    # Bind the promise accessor once without changing the cancellation callback.
    original = """    if constexpr (requires (T & p) {p.get_cancellation_slot();})
      h.promise().get_cancellation_slot().
      assign([c = getattr(task, "cancel")](webcpp::asio::cancellation_type ct) {
        py::gil_scoped_acquire lock;
        c();
      });"""
    replacement = """    if constexpr (requires (T & p) {p.get_cancellation_slot();}) {
      auto& promise = h.promise();
      promise.get_cancellation_slot().
      assign([c = getattr(task, "cancel")](webcpp::asio::cancellation_type ct) {
        py::gil_scoped_acquire lock;
        c();
      });
    }"""
    text = text.replace(original, replacement)
    text = re.sub(
        r"(\bctx\.run\(\);)", r"\1  // lint-run: preserve the upstream scheduler benchmark", text
    )
    return (
        "// Copyright (c) 2026 WebCpp.org\n//\n"
        "// Distributed under the Boost Software License, Version 1.0. (See\n"
        "// accompanying file LICENSE_1_0.txt or copy at\n"
        "// https://www.boost.org/LICENSE_1_0.txt)\n\n"
        "// Generated by test/applications/prepare.py. Do not edit.\n"
        "// Namespace/include migration; named accessor, formatting and lint annotations.\n"
        + text
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    manifest = json.loads((ROOT / "manifest.json").read_text())
    problems = inventory.validate(manifest, ROOT / "upstream")
    if problems:
        parser.exit(1, "\n".join(problems) + "\n")
    records = []
    for entry in manifest["applications"] + manifest["benchmarks"]:
        source = ROOT / "upstream" / entry["path"]
        text = migrate(source.read_text())
        output = ROOT / "migrated" / entry["path"]
        text = subprocess.run(
            [
                str(ROOT.parents[3] / ".local/wasi-sdk/bin/clang-format"),
                f"--assume-filename={output}",
            ],
            input=text,
            text=True,
            capture_output=True,
            check=True,
        ).stdout
        if args.check:
            if not output.exists() or output.read_text() != text:
                parser.exit(1, f"stale namespace migration: {output}\n")
        else:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(text)
        records.append(
            {
                "source": entry["path"],
                "original_sha256": entry["sha256"],
                "migrated_sha256": hashlib.sha256(text.encode()).hexdigest(),
            }
        )
    mapping = json.dumps({"source_form": "namespace-migration", "files": records}, indent=2) + "\n"
    path = ROOT / "migrated/mapping.json"
    if args.check:
        if path.read_text() != mapping:
            parser.exit(1, "stale migration mapping\n")
    else:
        path.write_text(mapping)
    print(f"Cobalt namespace migrations: {len(records)} verified")


if __name__ == "__main__":
    main()
