"""Generate separately identified script and native-binding corrections."""
import difflib
import hashlib
import json
from pathlib import Path
import subprocess
import sys

here = Path(__file__).resolve().parent
original = here.parent / "upstream/example/python.py"
expected = "63242af318ec0040b0bc1cc8daacbe96200332c485c42aaa935e6d426cc6c261"
assert hashlib.sha256(original.read_bytes()).hexdigest() == expected
text = original.read_text()
assert text.count("boost_async_example_python") == 3
corrected = (
    "# Copyright (c) 2026 WebCpp.org\n#\n# Distributed under the Boost Software License, Version"
    " 1.0. (See\n# accompanying file LICENSE_1_0.txt or copy at\n#"
    " https://www.boost.org/LICENSE_1_0.txt)\n\n# Generated by prepare.py. Do not edit.\n"
    + text.replace("boost_async_example_python", "boost_cobalt_example_python")
)
corrected = corrected.replace(
    "import boost_cobalt_example_python",
    "import importlib\nboost_cobalt_example_python = "
    'importlib.import_module("boost_cobalt_example_python")',
)
corrected = corrected.replace("\nasync def use_cpp", "\n\nasync def use_cpp").rstrip() + "\n"
outputs = {
    "corrected.py": corrected,
    "adaptation.json": (
        json.dumps(
            {
                "original_sha256": expected,
                "corrected_sha256": hashlib.sha256(corrected.encode()).hexdigest(),
                "change": (
                    "Replace the three stale module identifiers; preserve the example algorithm."
                ),
            },
            indent=2,
        )
        + "\n"
    ),
}

cpp = here.parent / "upstream/example/python.cpp"
manifest = json.loads((here.parent / "manifest.json").read_text())
cpp_hash = next(item["sha256"] for item in manifest["applications"] if item["id"] == "python")
assert hashlib.sha256(cpp.read_bytes()).hexdigest() == cpp_hash
binding = cpp.read_text()


def replace(before, after):
    global binding
    assert binding.count(before) == 1, before
    binding = binding.replace(before, after)


replace("except Exception as e:", "except BaseException as e:")
replace(
    "struct py_coroutine\n{",
    """// A fixture counter makes cancellation cleanup observable across the boundary.
static std::size_t live_python_coroutines = 0;

// A Future callback can outlive the C++ coroutine frame. Keep cancellation
// state separately owned and disarm it before that frame is destroyed.
struct python_cancellation
{
  asio::cancellation_signal signal;
  bool active = true;
};

void complete_future(py::object loop, py::object future, py::object value, bool error)
{
  loop.attr("call_soon")(py::cpp_function(
      [future = std::move(future), value = std::move(value), error]()
      {
        // Cancellation can win after C++ schedules completion but before
        // asyncio dispatches it. A completed Future must never be written twice.
        if (!py::cast<bool>(future.attr("done")()))
          future.attr(error ? "set_exception" : "set_result")(value);
      }));
}

struct py_coroutine
{""",
)
replace(
    "  struct promise_type\n  {",
    """  struct promise_type
  {
    std::shared_ptr<python_cancellation> cancellation = std::make_shared<python_cancellation>();
    promise_type() { ++live_python_coroutines; }
    asio::cancellation_slot get_cancellation_slot() { return cancellation->signal.slot(); }
    ~promise_type() { cancellation->active = false; --live_python_coroutines; }""",
)
replace(
    """      loop.attr("call_soon")(
          future.attr("set_exception"), translate_current_exception());""",
    """      cancellation->active = false;
      complete_future(loop, future, translate_current_exception(), true);""",
)
replace(
    """      done_ = true;
      loop.attr("call_soon")(
          future.attr("set_result"), py::cast(std::forward<T>(value)));""",
    """      done_ = true;
      cancellation->active = false;
      complete_future(loop, future, py::cast(std::forward<T>(value)), false);""",
)
replace(
    """      loop.attr("call_soon")(
          future.attr("set_result"), py::cast(std::forward<T>(value)));""",
    """      complete_future(loop, future, py::cast(std::forward<T>(value)), false);""",
)
replace(
    """    handle_->owner = this;
""",
    """    handle_->owner = this;
    handle_->future.attr("add_done_callback")(py::cpp_function(
        [state = handle_->cancellation](py::object completed)
        {
          if (state->active && py::cast<bool>(completed.attr("cancelled")()))
            state->signal.emit(asio::cancellation_type::all);
        }));
""",
)
replace(
    """    exception = getattr(task, "exception")();""",
    """    if (py::cast<bool>(task.attr("cancelled")()))
      exception = py::module_::import_("asyncio").attr("CancelledError")();
    else
      exception = getattr(task, "exception")();""",
)
replace(
    """    while not self.done:
        yield await self""",
    """    while not self.done:
        value = await self
        if not self.done:
            yield value""",
)
replace(
    "  namespace execution = asio::execution;",
    """  namespace execution = asio::execution;
  m.def("active_coroutines", [] { return live_python_coroutines; });""",
)
replace(
    """    if constexpr (requires (T & p) {p.get_cancellation_slot();})
      h.promise().get_cancellation_slot().
      assign([c = getattr(task, "cancel")](asio::cancellation_type ct) {
        py::gil_scoped_acquire lock;
        c();
      });""",
    """    if constexpr (requires (T & p) {p.get_cancellation_slot();}) {
      auto& promise = h.promise();
      promise.get_cancellation_slot().assign(
        [c = getattr(task, "cancel")](asio::cancellation_type ct) {
        py::gil_scoped_acquire lock;
        c();
      });
    }""",
)
binding = (
    "// Copyright (c) 2026 WebCpp.org\n//\n// Distributed under the Boost Software License, Version"
    " 1.0. (See\n// accompanying file LICENSE_1_0.txt or copy at\n//"
    " https://www.boost.org/LICENSE_1_0.txt)\n\n// Generated by prepare.py. Do not edit.\n"
    + binding
)
binding = subprocess.run(
    [
        str(here.parents[4] / ".local/wasi-sdk/bin/clang-format"),
        "--assume-filename=" + str(here / "binding.cpp"),
    ],
    input=binding,
    text=True,
    capture_output=True,
    check=True,
).stdout
outputs["binding.cpp"] = binding
outputs["binding.patch"] = "".join(
    difflib.unified_diff(
        cpp.read_text().splitlines(keepends=True),
        binding.splitlines(keepends=True),
        fromfile="upstream/example/python.cpp",
        tofile="python/binding.cpp",
    )
)
outputs["binding-adaptation.json"] = (
    json.dumps(
        {
            "original_sha256": cpp_hash,
            "adapted_sha256": hashlib.sha256(binding.encode()).hexdigest(),
            "changes": [
                "Do not yield the terminal None from the Python async iterator.",
                "Ignore delayed delivery into an already completed Future.",
                "Propagate outer Future cancellation through the Cobalt cancellation slot.",
                "Translate inner asyncio cancellation without losing the awaiting coroutine.",
            ],
        },
        indent=2,
    )
    + "\n"
)
for name, content in outputs.items():
    path = here / name
    if "--check" in sys.argv:
        assert path.read_text() == content, f"{path} is stale; run prepare.py"
    else:
        path.write_text(content)
