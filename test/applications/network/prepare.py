"""Generate controlled-endpoint counterparts without changing upstream sources."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
import subprocess

import normalize

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import importlib

namespace_migration = importlib.import_module("prepare")
import inventory  # noqa: E402

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--clang-format", required=True)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
manifest = json.loads((HERE.parent / "manifest.json").read_text())
assert not inventory.validate(manifest, HERE.parent / "upstream")


def replace(text, old, new):
    assert old in text, old
    return text.replace(old, new)


records = []
for name in ("http", "ticker", "echo_server"):
    source = HERE.parent / "upstream/example" / (name + ".cpp")
    original = source.read_text()
    text = original
    if name == "echo_server":
        text = replace(text, "55555", "webcpp_fixture::listener_port()")
    else:
        text = replace(
            text, '"https", cobalt::use_op', "webcpp_fixture::remote_port(), cobalt::use_op"
        )
        text = (
            replace(text, "resolve.async_resolve(host,", 'resolve.async_resolve("127.0.0.1",')
            if name == "http"
            else replace(text, "res.async_resolve(host,", 'res.async_resolve("127.0.0.1",')
        )
        declaration = (
            "ssl_socket_type sock{cobalt::this_thread::get_executor(), ctx};"
            if name == "http"
            else "asio::ssl::stream<socket_type> sock{cobalt::this_thread::get_executor(), ctx};"
        )
        text = replace(
            text,
            declaration,
            declaration
            + "\n"
            "  sock.set_verify_mode(boost::asio::ssl::verify_peer);\n"
            '  sock.set_verify_callback(boost::asio::ssl::host_name_verification("localhost"));\n'
            '  if (SSL_set_tlsext_host_name(sock.native_handle(), "localhost") != 1) {\n'
            "    std::abort();\n  }",
        )
        context = (
            "boost::asio::ssl::context ctx{boost::asio::ssl::context::tls_client};"
            if name == "http"
            else "asio::ssl::context ctx{asio::ssl::context_base::tls_client};"
        )
        text = replace(
            text, context, context + "\n  ctx.load_verify_file(webcpp_fixture::ca_file());"
        )
        if name == "ticker":
            text = replace(text, "8080)", "webcpp_fixture::listener_port())")
    # Fully qualified SSL names keep both the original and the migrated form valid.
    preamble = '#include "fixture.hpp"\n#include <boost/asio/ssl/host_name_verification.hpp>\n'
    if name == "echo_server":
        preamble = '#include "fixture.hpp"\n'
    for form in ("oracle", "port"):
        content = preamble + text
        content = (
            "// Copyright (c) 2026 WebCpp.org\n//\n"
            "// Distributed under the Boost Software License, Version 1.0. (See\n"
            "// accompanying file LICENSE_1_0.txt or copy at\n"
            "// https://www.boost.org/LICENSE_1_0.txt)\n\n"
            "// Generated by network/prepare.py. Do not edit.\n"
            "// Controlled endpoints and verified TLS; see mapping.json.\n"
            + content
        )
        output = HERE / form / (name + ".cpp")
        output.parent.mkdir(exist_ok=True)
        content = subprocess.run(
            [args.clang_format, f"--assume-filename={output}"],
            input=content,
            text=True,
            capture_output=True,
            check=True,
        ).stdout
        content = normalize.apply(name, content)
        if form == "port":
            content = namespace_migration.migrate(content)
        content = subprocess.run(
            [args.clang_format, f"--assume-filename={output}"], input=content,
            text=True, capture_output=True, check=True).stdout
        if args.check:
            if not output.is_file() or output.read_text() != content:
                parser.exit(1, f"stale network counterpart: {output}\n")
        else:
            output.write_text(content)
        records.append(
            {
                "name": name,
                "form": form,
                "original_sha256": hashlib.sha256(original.encode()).hexdigest(),
                "counterpart_sha256": hashlib.sha256(content.encode()).hexdigest(),
            }
        )
mapping = (
    json.dumps(
        {
            "source_form": "controlled-endpoint-counterpart",
            "files": records,
            "adaptations": [
                "Select loopback peer/listener ports through fixture environment variables.",
                "Resolve the numeric loopback endpoint using the real resolver.",
                "Require the fixture CA, localhost identity verification and SNI.",
                "Apply reviewed style normalization; preserve explicit output flushing.",
                (
                    "Terminate the original infinite listeners after witnessed traffic; "
                    "this is not graceful application shutdown evidence."
                ),
            ],
        },
        indent=2,
    )
    + "\n"
)
mapping_path = HERE / "mapping.json"
if args.check:
    if mapping_path.read_text() != mapping:
        parser.exit(1, "stale network mapping\n")
else:
    mapping_path.write_text(mapping)
print("Verified six controlled network counterparts.")
