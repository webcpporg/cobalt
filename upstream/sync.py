"""Maintain native originals and shipped Wasm Cobalt. Never run in a consumer build."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
BUNDLE = ROOT / "upstream"


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def relocate(text: str) -> str:
    text = text.replace("<boost/cobalt.hpp>", "<webcpp/cobalt/detail/backend.hpp>")
    text = text.replace("boost/cobalt/", "webcpp/cobalt/detail/backend/")
    text = text.replace("boost/asio/", "webcpp/asio/detail/backend/")
    text = re.sub(
        r"namespace boost\s*\{\s*namespace cobalt\s*\{",
        "namespace webcpp { namespace cobalt {",
        text,
    )
    text = text.replace("boost::cobalt", "webcpp::cobalt")
    text = re.sub(r"(?<!\w)(?:::)?boost::asio\b", "::webcpp::asio_backend", text)
    text = re.sub(r"(?<![\w:])asio::", "::webcpp::asio_backend::", text)
    text = re.sub(r"(?<![\w:])cobalt::", "::webcpp::cobalt::", text)
    text = re.sub(r"(?<![\w:])system::", "::boost::system::", text)
    text = text.replace("namespace ::webcpp::", "namespace webcpp::")
    text = text.replace("BOOST_ASIO_", "WEBCPP_ASIO_BACKEND_")
    text = text.replace("BOOST_DETAIL_COBALT_", "WEBCPP_COBALT_BACKEND_DETAIL_")
    return text.replace("BOOST_COBALT_", "WEBCPP_COBALT_BACKEND_")


def outputs(headers: Path, sources: Path) -> dict[str, bytes]:
    pin = json.loads((BUNDLE / "pin.json").read_text())
    original: dict[str, bytes] = {}
    for name, expected in pin["files"].items():
        path = (headers if name.startswith("boost/") else sources) / name
        data = path.read_bytes()
        if digest(data) != expected:
            raise ValueError("upstream file differs from pinned Cobalt 1.92: " + name)
        original[name] = data
    adapted = dict(original)
    with tempfile.TemporaryDirectory(prefix="webcpp-cobalt-import-") as temporary:
        stage = Path(temporary)
        for name, data in original.items():
            path = stage / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        for correction in pin["corrections"]:
            bundle = BUNDLE / correction
            manifest = json.loads((bundle / "manifest.json").read_text())
            for name, hashes in manifest["files"].items():
                if digest((stage / name).read_bytes()) != hashes["before"]:
                    raise ValueError("correction input differs: " + name)
            subprocess.run(
                ["git", "apply", "--no-index", str(bundle / "boost-1.92.patch")],
                cwd=stage,
                check=True,
                capture_output=True,
                text=True,
            )
            for name, hashes in manifest["files"].items():
                data = (stage / name).read_bytes()
                if digest(data) != hashes["after"]:
                    raise ValueError("correction output differs: " + name)
                adapted[name] = data
    adapted["libs/cobalt/src/main.cpp"] = (BUNDLE / "adaptations/main.cpp").read_bytes()
    adapted["boost/cobalt/detail/sbo_resource.hpp"] = (
        BUNDLE / "adaptations/sbo_resource.hpp"
    ).read_bytes()
    result: dict[str, bytes] = {}
    banner = (
        "// Generated by upstream/sync.py; edit its pinned inputs, not this file.\n"
        "#include <webcpp/cobalt/config.hpp>\n"
    )
    # Owner-approved exception to native identity: the SSL state machine must
    # retain the checked fixes, while its coroutine/socket dependencies stay Boost.
    for original_name, destination in (
        ("boost/cobalt/io/ssl.hpp", "include/webcpp/cobalt/detail/native_ssl.hpp"),
        ("libs/cobalt/src/io/ssl.cpp", "src/native_ssl.cpp"),
    ):
        ssl = adapted[original_name].decode()
        ssl = ssl.replace("namespace boost::cobalt::io::ssl", "namespace webcpp::cobalt::io::ssl")
        ssl = re.sub(r"(?<![\w:])system::", "::boost::system::", ssl)
        ssl = ssl.replace("BOOST_COBALT_IO_SSL_HPP", "WEBCPP_COBALT_DETAIL_NATIVE_SSL_HPP")
        ssl = ssl.replace("<boost/cobalt/io/ssl.hpp>", "<webcpp/cobalt/detail/native_ssl.hpp>")
        ssl = re.sub(
            r"#if !defined\(BOOST_COBALT_SSL_SOURCE\).*?#include"
            r" <boost/config/auto_link.hpp>\n#endif",
            "// Link WebCPP's corrected SSL archive explicitly.",
            ssl,
            flags=re.S,
        )
        if original_name.endswith(".hpp"):
            ssl = ssl.replace(
                "namespace webcpp::cobalt::io::ssl",
                "namespace webcpp::cobalt::detail { struct native_ssl_read; struct"
                " native_ssl_write; }\nnamespace webcpp::cobalt::io::ssl",
                1,
            )
            ssl = ssl.replace(
                "  // Plain TCP is allowed only",
                "  friend struct ::webcpp::cobalt::detail::native_ssl_read;\n"
                "  friend struct ::webcpp::cobalt::detail::native_ssl_write;\n"
                "  // Plain TCP is allowed only",
                1,
            )
        result[destination] = (banner + ssl).encode()
    for name, data in adapted.items():
        text = relocate(data.decode())
        if name == "boost/cobalt/detail/main.hpp":
            # All pinned Wasm ABIs need the upstream C-linkage entry point.
            # Scope Clang's diagnostic suppression to that one declaration.
            text = text.replace(
                "defined(__clang__) && defined(__wasip3__)",
                "defined(__clang__) && defined(__wasm__)",
            )
        if name == "boost/cobalt/io/endpoint.hpp":
            text = text.replace(
                "static_protocol<Family, Type, Protocol> proto,",
                "[[maybe_unused]] static_protocol<Family, Type, Protocol> proto,",
            )
        if name == "boost/cobalt/io/acceptor.hpp":
            text = text.replace(
                "static_protocol<F, tcp.type(), P> stream_proto = tcp",
                "[[maybe_unused]] static_protocol<F, tcp.type(), P> stream_proto = tcp",
            )
        if name.startswith("libs/cobalt/src/"):
            relative = name.removeprefix("libs/cobalt/src/")
            result["src/native/" + relative] = original[name]
            path = "src/wasm/" + relative
        elif name == "boost/cobalt.hpp":
            path = "include/webcpp/cobalt/detail/backend.hpp"
        else:
            relative = name.removeprefix("boost/cobalt/")
            path = "include/webcpp/cobalt/detail/backend/" + relative
            if relative == "config.hpp":
                text = (
                    "#include <webcpp/cobalt/config.hpp>\n"
                    "namespace boost {}\n"
                    "namespace webcpp::cobalt { using namespace ::boost; }\n"
                    + text
                )
            elif not relative.startswith("detail/"):
                guard = "WEBCPP_COBALT_FORWARD_" + re.sub(r"[^A-Z0-9]", "_", relative.upper())
                requirements = {
                    "io.hpp": (
                        "SOCKET_BACKEND",
                        (
                            "raw TCP/UDP requires native/WASI; use individual portable I/O headers"
                            " or browser transports"
                        ),
                    ),
                    "io/acceptor.hpp": (
                        "SOCKET_BACKEND",
                        "raw TCP/UDP requires native/WASI; browsers do not expose TCP listeners",
                    ),
                    "io/socket.hpp": (
                        "SOCKET_BACKEND",
                        "raw TCP/UDP requires native/WASI; use a browser transport",
                    ),
                    "io/stream_socket.hpp": (
                        "SOCKET_BACKEND",
                        "raw TCP/UDP requires native/WASI; use a browser transport",
                    ),
                    "io/datagram_socket.hpp": (
                        "SOCKET_BACKEND",
                        "raw TCP/UDP requires native/WASI; use a browser transport",
                    ),
                    "io/seq_packet_socket.hpp": (
                        "LOCAL_SOCKETS",
                        "sequenced-packet sockets require native support",
                    ),
                    "io/signal_set.hpp": (
                        "SIGNALS",
                        "process signals require a native target; use application cancellation",
                    ),
                    "io/serial_port.hpp": (
                        "SERIAL_PORT",
                        "serial ports require native support or a separate host adapter",
                    ),
                    "thread.hpp": (
                        "THREADS",
                        "thread requires a supported pthread or cooperative-thread profile",
                    ),
                    "io/ssl.hpp": (
                        "OPENSSL_BACKEND",
                        "guest SSL requires native/WASI OpenSSL; browser TLS belongs to HTTPS/WSS",
                    ),
                }
                requirement = ""
                if relative in requirements:
                    capability, reason = requirements[relative]
                    requirement = (
                        f"#if !WEBCPP_COBALT_HAS_{capability}\n"
                        f'#error "webcpp::cobalt: {reason}"\n#else\n'
                    )
                result["include/webcpp/cobalt/" + relative] = (
                    banner
                    + f"#ifndef {guard}\n#define {guard}\n"
                    "#include <webcpp/cobalt/config.hpp>\n"
                    "#ifdef WEBCPP_TARGET_NATIVE\n"
                    f"#include <boost/cobalt/{relative}>\n#else\n"
                    + requirement
                    + f"#include <webcpp/cobalt/detail/backend/{relative}>\n"
                    + ("#endif\n" if requirement else "")
                    + "#endif\n#endif\n"
                ).encode()
                if relative == "io/ssl.hpp":
                    public_path = "include/webcpp/cobalt/" + relative
                    result[public_path] = result[public_path].replace(
                        b"<boost/cobalt/io/ssl.hpp>",
                        b"<webcpp/cobalt/detail/native_ssl.hpp>\n"
                        b"#include <webcpp/cobalt/detail/native_ssl_transfer.hpp>",
                    )
        result[path] = (banner + text).encode()
    source_names = sorted(
        name.removeprefix("libs/cobalt/src/")
        for name in original
        if name.startswith("libs/cobalt/src/")
    )
    native_core = [
        "src/native/" + name for name in source_names if name not in ("main.cpp", "io/ssl.cpp")
    ]
    native_core.append("src/native_version.cpp")
    wasi_omitted = {
        "main.cpp",
        "thread.cpp",
        "io/ssl.cpp",
        "io/signal_set.cpp",
        "io/serial_port.cpp",
        "io/seq_packet_socket.cpp",
    }
    wasm_common = ["src/wasm/" + name for name in source_names if name not in wasi_omitted]
    # These POSIX APIs do not become browser facilities merely because libc
    # declares some related types. Public headers diagnose unsupported use.
    browser_extra = []
    contract = {"schema": 1, "boost_version": "1.92.0", "profiles": {}}
    for target in ("native", "wasip2", "wasip3", "emscripten"):
        directory = "native" if target == "native" else "wasm"
        contract["profiles"][target] = {
            "core": (
                native_core
                if target == "native"
                else wasm_common + (browser_extra if target == "emscripten" else [])
            ),
            "multi_add": [] if target == "native" else ["src/wasm/thread.cpp"],
            "runner": [f"src/{directory}/main.cpp"],
            "ssl": (
                []
                if target == "emscripten"
                else (
                    ["src/native_ssl.cpp", "src/native_ssl_transfer.cpp"]
                    if target == "native"
                    else ["src/wasm/io/ssl.cpp"]
                )
            ),
        }
    result["sources.json"] = (json.dumps(contract, indent=2) + "\n").encode()
    jam = (
        "# Copyright (c) 2026 WebCpp.org\n#\n# Distributed under the Boost Software License,"
        " Version 1.0. (See\n# accompanying file LICENSE_1_0.txt or copy at\n#"
        " https://www.boost.org/LICENSE_1_0.txt)\n"
    )
    jam += "# Generated by upstream/sync.py from the same inventory as sources.json.\n"
    for variable, files in (
        ("NATIVE_CORE", native_core),
        ("WASM_COMMON", wasm_common),
        ("BROWSER_EXTRA", browser_extra),
    ):
        jam += (
            variable
            + " =\n    "
            + "\n    ".join(name.removeprefix("src/") for name in files)
            + "\n    ;\n"
        )
    result["src/sources.jam"] = jam.encode()
    result["upstream/generated.json"] = (
        json.dumps({name: digest(data) for name, data in sorted(result.items())}, indent=2) + "\n"
    ).encode()
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--boost-include", type=Path, required=True)
    parser.add_argument("--boost-source", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        generated = outputs(args.boost_include, args.boost_source)
        for name, data in generated.items():
            path = ROOT / name
            if args.check:
                if not path.is_file() or path.read_bytes() != data:
                    raise ValueError("generated file is stale: " + name)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        parser.exit(1, str(error) + "\n")
    print(
        f"Cobalt shipped sources: {len(generated)} files {'verified' if args.check else 'written'}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
